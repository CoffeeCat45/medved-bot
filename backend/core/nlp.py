import re

#импорт LLM

def extract_symptoms(text: str) -> dict:
    text_lower = text.lower()
    # 1 Пытаемся понять категорию по ключевым словам
    categories_map = {
        "лор": ["горло", "насморк", "ухо", "гланды", "кашель", "чихание", "заложило нос"],
        "глаза": ["глаз", "зрение", "зуд в глазах", "покраснение глаз", "слезятся"],
        "жкт": ["живот", "тошнит", "рвота", "понос", "запор", "желудок", "кишечник", "изжога"],
        "кожа": ["кожа", "сыпь", "зуд", "покраснение", "прыщи", "волдыри", "чешется"],
        "неврология": ["голова", "мигрень", "головокружение", "онемение", "нервы", "затылок", "висок"],
        "дыхание": ["одышка", "нехватка воздуха", "бронхи", "тяжело дышать", "свист в груди"],
        "травма": ["ушиб", "перелом", "порез", "ударился", "растяжение", "вывих"],
        "психиатрия": ["тревога", "паника", "депрессия", "бессонница", "страх", "нервный срыв"]
    }
    detected_category = "боль" # По умолчанию
    for cat, words in categories_map.items():
        if any(word in text_lower for word in words):
            detected_category = cat
            break

    # 2 Локализация
    localization = ""
    loc_keywords = ["голова", "живот", "грудь", "горло", "спина", "нога", "рука", "глаз", "ухо"]
    for loc in loc_keywords:
        if loc in text_lower:
            localization = loc
            break

    return {
        "category": detected_category,
        "localization": localization,
        "original_text": text
    }